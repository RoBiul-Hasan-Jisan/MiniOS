"""
Hardware Port Definitions
"""

# I/O Port addresses
PORT_PIC1_COMMAND = 0x20
PORT_PIC1_DATA = 0x21
PORT_PIC2_COMMAND = 0xA0
PORT_PIC2_DATA = 0xA1

PORT_KEYBOARD_DATA = 0x60
PORT_KEYBOARD_STATUS = 0x64
PORT_KEYBOARD_COMMAND = 0x64

PORT_VGA_INDEX = 0x3D4
PORT_VGA_DATA = 0x3D5

PORT_SERIAL_COM1 = 0x3F8
PORT_SERIAL_COM2 = 0x2F8
PORT_SERIAL_COM3 = 0x3E8
PORT_SERIAL_COM4 = 0x2E8

PORT_CMOS_INDEX = 0x70
PORT_CMOS_DATA = 0x71

PORT_PIT_CHANNEL0 = 0x40
PORT_PIT_CHANNEL1 = 0x41
PORT_PIT_CHANNEL2 = 0x42
PORT_PIT_COMMAND = 0x43

# DMA Controller ports
PORT_DMA1_CHAN0_ADDR = 0x00
PORT_DMA1_CHAN0_COUNT = 0x01
PORT_DMA1_CHAN1_ADDR = 0x02
PORT_DMA1_CHAN1_COUNT = 0x03
PORT_DMA1_CHAN2_ADDR = 0x04
PORT_DMA1_CHAN2_COUNT = 0x05
PORT_DMA1_CHAN3_ADDR = 0x06
PORT_DMA1_CHAN3_COUNT = 0x07
PORT_DMA1_STATUS = 0x08
PORT_DMA1_COMMAND = 0x08
PORT_DMA1_REQUEST = 0x09
PORT_DMA1_MASK = 0x0A
PORT_DMA1_MODE = 0x0B
PORT_DMA1_CLEAR = 0x0C